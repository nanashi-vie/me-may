CREATE SEQUENCE book_code_seq NO CYCLE;
CREATE TABLE category (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(32) UNIQUE NOT NULL, name VARCHAR(100) NOT NULL, slug VARCHAR(100) UNIQUE NOT NULL, sort_order INTEGER NOT NULL
);
CREATE TABLE book_copy (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 book_code VARCHAR(32) UNIQUE NOT NULL,
 title VARCHAR(300), isbn VARCHAR(32), publisher VARCHAR(200), author VARCHAR(200), language VARCHAR(50),
 binding VARCHAR(16) CHECK(binding IN ('PAPERBACK','HARDCOVER')),
 condition_grade VARCHAR(16) CHECK(condition_grade IN ('VERY_GOOD','GOOD','FAIR')), condition_note VARCHAR(4000),
 availability VARCHAR(16) NOT NULL DEFAULT 'AVAILABLE' CHECK(availability IN ('AVAILABLE','SOLD')),
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE listing (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 book_copy_id BIGINT UNIQUE NOT NULL REFERENCES book_copy(id), slug VARCHAR(80) UNIQUE NOT NULL,
 price_vnd BIGINT CHECK(price_vnd BETWEEN 1 AND 999999999999), description VARCHAR(10000), category_id BIGINT REFERENCES category(id),
 reading_level VARCHAR(8) CHECK(reading_level IN ('PRE_A1','A1','A2','B1','B2','C1','C2')), reading_level_basis VARCHAR(1000), reading_video_url VARCHAR(2048),
 publication_status VARCHAR(16) NOT NULL DEFAULT 'DRAFT' CHECK(publication_status IN ('DRAFT','PUBLISHED','ARCHIVED')),
 published_at TIMESTAMPTZ, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE collection (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL,
 slug VARCHAR(120) UNIQUE NOT NULL, sort_order INTEGER NOT NULL DEFAULT 0 CHECK(sort_order>=0), active BOOLEAN NOT NULL DEFAULT TRUE,
 version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE listing_age_group (
 listing_id BIGINT NOT NULL REFERENCES listing(id), age_group VARCHAR(16) NOT NULL CHECK(age_group IN ('AGE_0_3','AGE_4_6','AGE_7_9','AGE_10_PLUS')), PRIMARY KEY(listing_id,age_group)
);
CREATE TABLE listing_collection (
 listing_id BIGINT NOT NULL REFERENCES listing(id), collection_id BIGINT NOT NULL REFERENCES collection(id), PRIMARY KEY(listing_id,collection_id)
);
CREATE TABLE book_media (
 id UUID PRIMARY KEY, book_copy_id BIGINT NOT NULL REFERENCES book_copy(id),
 role VARCHAR(16) NOT NULL CHECK(role IN ('FRONT','BACK','INSIDE')), state VARCHAR(16) NOT NULL CHECK(state IN ('UPLOADING','ACTIVE','DELETE_PENDING')),
 storage_public_id VARCHAR(300) UNIQUE NOT NULL, asset_id VARCHAR(200), format VARCHAR(16), bytes BIGINT, width INTEGER, height INTEGER,
 alt VARCHAR(300), source_ref VARCHAR(500),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX media_active_slot ON book_media(book_copy_id,role) WHERE state='ACTIVE';
CREATE INDEX media_cleanup ON book_media(state,updated_at);
CREATE TABLE audit_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id BIGINT NOT NULL REFERENCES admin_user(id),
 target_type VARCHAR(32) NOT NULL, target_id BIGINT NOT NULL, action VARCHAR(40) NOT NULL,
 before_data JSONB NOT NULL DEFAULT '{}', after_data JSONB NOT NULL DEFAULT '{}', aggregate_version BIGINT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX audit_target ON audit_event(target_type,target_id,created_at DESC,id DESC);
CREATE INDEX listing_publication ON listing(publication_status,published_at);
CREATE INDEX book_availability ON book_copy(availability);
CREATE INDEX book_updated ON book_copy(updated_at DESC,id DESC);
CREATE INDEX collection_membership ON listing_collection(collection_id);
