CREATE TABLE order_action_notes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES orders(id), operation VARCHAR(40) NOT NULL,
 reason VARCHAR(1000) NOT NULL CHECK(length(btrim(reason))>0),
 order_version BIGINT NOT NULL CHECK(order_version>=0), request_id UUID NOT NULL,
 actor_id BIGINT NOT NULL REFERENCES admin_user(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(order_id,operation,request_id)
);
CREATE INDEX order_note_parent ON order_action_notes(order_id,id);
