CREATE TABLE customer (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_code VARCHAR(20) GENERATED ALWAYS AS ('KH-' || CASE WHEN id < 1000000 THEN lpad(id::text,6,'0') ELSE id::text END) STORED UNIQUE NOT NULL,
 full_name VARCHAR(150) NOT NULL CHECK (length(btrim(full_name)) > 0),
 phone VARCHAR(20),
 default_address TEXT CHECK (length(default_address) <= 500),
 zalo_name VARCHAR(150), tiktok_id VARCHAR(100), threads_id VARCHAR(100),
 note TEXT CHECK (length(note) <= 1000),
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','ARCHIVED')),
 version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
 created_by BIGINT REFERENCES admin_user(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX customer_phone_idx ON customer(phone);
CREATE INDEX customer_status_created_idx ON customer(status,created_at DESC,id DESC);
CREATE INDEX customer_created_idx ON customer(created_at DESC,id DESC);
