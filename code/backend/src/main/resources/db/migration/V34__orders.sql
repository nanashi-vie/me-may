CREATE TABLE orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_code VARCHAR(24) GENERATED ALWAYS AS ('DH-' || CASE WHEN id<1000000 THEN lpad(id::text,6,'0') ELSE id::text END) STORED UNIQUE NOT NULL,
 customer_id BIGINT NOT NULL REFERENCES customer(id), customer_code_snapshot VARCHAR(20) NOT NULL,
 customer_name_snapshot VARCHAR(150) NOT NULL, customer_phone_snapshot VARCHAR(20),
 status VARCHAR(24) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','KEEPING','READY_TO_SHIP','COMPLETED','UNSUCCESSFUL','CANCELLED')),
 fulfillment_type VARCHAR(16) NOT NULL DEFAULT 'IMMEDIATE' CHECK(fulfillment_type IN ('IMMEDIATE','KEEP')),
 keep_started_at TIMESTAMPTZ, keep_until TIMESTAMPTZ, keep_extension_count INTEGER NOT NULL DEFAULT 0 CHECK(keep_extension_count>=0),
 required_deposit_vnd BIGINT NOT NULL DEFAULT 100000 CHECK(required_deposit_vnd BETWEEN 0 AND 9007199254740991),
 deposit_override_reason VARCHAR(1000), deposit_override_by BIGINT REFERENCES admin_user(id), deposit_override_at TIMESTAMPTZ,
 discount_amount BIGINT NOT NULL DEFAULT 0 CHECK(discount_amount BETWEEN 0 AND 9007199254740991),
 recipient_name VARCHAR(150), recipient_phone VARCHAR(20), shipping_address VARCHAR(500),
 shipping_provider VARCHAR(20) NOT NULL DEFAULT 'J&T', shipping_service VARCHAR(20) NOT NULL DEFAULT 'EXPRESS',
 shipping_payment_type VARCHAR(16) NOT NULL DEFAULT 'PP_CASH' CHECK(shipping_payment_type IN ('PP_CASH','CC_CASH','PP_PM')),
 shipping_fee BIGINT CHECK(shipping_fee BETWEEN 0 AND 9007199254740991),
 parcel_weight_grams BIGINT CHECK(parcel_weight_grams BETWEEN 1 AND 9007199254740991),
 parcel_weight_overridden BOOLEAN NOT NULL DEFAULT FALSE, parcel_weight_needs_review BOOLEAN NOT NULL DEFAULT FALSE,
 parcel_count INTEGER NOT NULL DEFAULT 1 CHECK(parcel_count=1),
 cod_amount BIGINT NOT NULL DEFAULT 0 CHECK(cod_amount BETWEEN 0 AND 9007199254740991), cod_needs_review BOOLEAN NOT NULL DEFAULT TRUE,
 declared_value BIGINT CHECK(declared_value BETWEEN 0 AND 9007199254740991), tracking_code VARCHAR(100),
 completed_at TIMESTAMPTZ, completed_by BIGINT REFERENCES admin_user(id),
 failed_at TIMESTAMPTZ, failed_by BIGINT REFERENCES admin_user(id), failure_reason VARCHAR(1000),
 cancelled_at TIMESTAMPTZ, cancelled_by BIGINT REFERENCES admin_user(id), cancellation_reason VARCHAR(1000),
 created_by BIGINT REFERENCES admin_user(id), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0)
);
CREATE INDEX order_created ON orders(created_at DESC,id DESC);
CREATE INDEX order_customer ON orders(customer_id,created_at DESC,id DESC);
CREATE INDEX order_status ON orders(status,created_at DESC,id DESC);
CREATE INDEX order_keep ON orders(keep_until) WHERE status='KEEPING';
ALTER TABLE listing ADD CONSTRAINT listing_order_reference UNIQUE(id,book_copy_id);
CREATE TABLE order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 source_type VARCHAR(16) NOT NULL CHECK(source_type IN ('CATALOG','MANUAL')),
 book_copy_id BIGINT REFERENCES book_copy(id), listing_id BIGINT, book_code_snapshot VARCHAR(32),
 title_snapshot VARCHAR(300) NOT NULL CHECK(length(btrim(title_snapshot))>0),
 unit_price_vnd BIGINT NOT NULL CHECK(unit_price_vnd BETWEEN 0 AND 999999999999),
 quantity BIGINT NOT NULL CHECK(quantity BETWEEN 1 AND 999999),
 unit_weight_grams BIGINT CHECK(unit_weight_grams BETWEEN 1 AND 9007199254740991),
 manual_match_override_reason VARCHAR(1000), manual_match_evidence VARCHAR(128),
 created_by BIGINT NOT NULL REFERENCES admin_user(id), added_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,order_id), FOREIGN KEY(listing_id,book_copy_id) REFERENCES listing(id,book_copy_id),
 CHECK((source_type='CATALOG' AND book_copy_id IS NOT NULL AND listing_id IS NOT NULL) OR
       (source_type='MANUAL' AND book_copy_id IS NULL AND listing_id IS NULL))
);
CREATE INDEX order_item_parent ON order_items(order_id,id);
CREATE INDEX order_item_book ON order_items(book_copy_id);
CREATE TABLE order_reservation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 book_copy_id BIGINT NOT NULL REFERENCES book_copy(id), quantity BIGINT NOT NULL CHECK(quantity>=0),
 state VARCHAR(16) NOT NULL CHECK(state IN ('ACTIVE','RELEASED','CONSUMED')),
 returned_quantity BIGINT NOT NULL DEFAULT 0 CHECK(returned_quantity>=0),
 restocked_quantity BIGINT NOT NULL DEFAULT 0 CHECK(restocked_quantity>=0 AND restocked_quantity<=returned_quantity),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(order_id,book_copy_id), CHECK(state<>'ACTIVE' OR quantity>0), CHECK(returned_quantity<=quantity)
);
CREATE INDEX order_reserved_book ON order_reservation(book_copy_id,state);
CREATE TABLE order_payments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 transaction_type VARCHAR(16) NOT NULL CHECK(transaction_type IN ('DEPOSIT','PAYMENT','REFUND')),
 amount BIGINT NOT NULL CHECK(amount BETWEEN 1 AND 9007199254740991),
 payment_method VARCHAR(24) NOT NULL CHECK(payment_method IN ('CASH','BANK_TRANSFER','OTHER')),
 occurred_at TIMESTAMPTZ NOT NULL, note VARCHAR(1000), created_by BIGINT NOT NULL REFERENCES admin_user(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 voided_at TIMESTAMPTZ, voided_by BIGINT REFERENCES admin_user(id), void_reason VARCHAR(1000),
 CHECK((voided_at IS NULL AND voided_by IS NULL AND void_reason IS NULL) OR
       (voided_at IS NOT NULL AND voided_by IS NOT NULL AND length(btrim(void_reason))>0))
);
CREATE INDEX order_payment_parent ON order_payments(order_id,id);
CREATE TABLE order_shipments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 attempt_no INTEGER NOT NULL CHECK(attempt_no>0),
 state VARCHAR(20) NOT NULL CHECK(state IN ('PLANNED','HANDED_OVER','FAILED','ABORTED')),
 shipping_snapshot JSONB NOT NULL, tracking_code VARCHAR(100),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, handed_over_at TIMESTAMPTZ,
 handed_over_by BIGINT REFERENCES admin_user(id), failed_at TIMESTAMPTZ, failed_by BIGINT REFERENCES admin_user(id), failure_reason VARCHAR(1000),
 UNIQUE(order_id,attempt_no)
);
CREATE UNIQUE INDEX order_one_planned ON order_shipments(order_id) WHERE state='PLANNED';
CREATE TABLE order_returns (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 item_id BIGINT NOT NULL, quantity_received BIGINT NOT NULL CHECK(quantity_received>=0),
 quantity_restocked BIGINT NOT NULL CHECK(quantity_restocked BETWEEN 0 AND quantity_received),
 reason VARCHAR(1000) NOT NULL CHECK(length(btrim(reason))>0), created_by BIGINT NOT NULL REFERENCES admin_user(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, request_id UUID NOT NULL,
 FOREIGN KEY(item_id,order_id) REFERENCES order_items(id,order_id), UNIQUE(order_id,item_id)
);
CREATE TABLE order_mutation_receipt (
 actor_id BIGINT NOT NULL REFERENCES admin_user(id), operation VARCHAR(64) NOT NULL,
 request_id UUID NOT NULL, order_id BIGINT REFERENCES orders(id), fingerprint VARCHAR(64) NOT NULL,
 result_json JSONB, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(actor_id,operation,request_id)
);
